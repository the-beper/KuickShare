#!/usr/bin/env python3
"""Helper for the gettext catalogs in po/ (stdlib only).

  po.py todo                 pending entries (untranslated or fuzzy) of every language, as JSON
  po.py apply FILE.json      write translations, in the format of `todo` plus "msgstr"
  po.py status               pending count per language

`todo` prints {"<lang>": [{"msgid": ..., "context": ..., "msgid_plural": ..., "forms": N}, ...]};
"context" is there only for a message with a msgctxt, "msgid_plural" and "forms" only for a plural
one. `apply` takes the same objects, each with "msgstr": a string, or for a plural message a list of
N strings, one per plural form of the language. It matches the message by msgid and context, clears
the fuzzy flag and leaves everything else alone; it writes nothing if an object matches no message
or its msgstr does not fit. The catalogs are regenerated by `build/build-env.sh po/extract.sh`,
never edited by hand.
"""

import json
import re
import sys
from pathlib import Path

PO_DIR = Path(__file__).resolve().parents[2] / "po"
KEYWORD = re.compile(r"^(msgctxt|msgid_plural|msgid|msgstr(?:\[\d+\])?) ")


def languages() -> list[str]:
    return (PO_DIR / "LINGUAS").read_text().split()


ESCAPES = {"n": "\n", "t": "\t", '"': '"', "\\": "\\"}


def unquote(lines: list[str]) -> str:
    """Joins the quoted pieces of a field and resolves its escapes."""
    out = ""
    for line in lines:
        match = re.match(r'^(?:msgctxt|msgid_plural|msgid|msgstr(?:\[\d+\])?)?\s*"(.*)"$', line)
        if match:
            out += match.group(1)
    return re.sub(r"\\(.)", lambda m: ESCAPES.get(m.group(1), m.group(0)), out)


def quote(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
    return '"' + escaped + '"'


def parse(block: str) -> tuple[list[str], dict[str, list[str]]] | None:
    """Splits an entry into its comment lines and its fields (msgctxt, msgid, msgid_plural, msgstr
    or msgstr[N]), each with its source lines; None for blocks without a msgid (obsolete entries)."""
    comments: list[str] = []
    fields: dict[str, list[str]] = {}
    key = None
    for line in block.split("\n"):
        match = KEYWORD.match(line)
        if match:
            key = match.group(1)
            fields[key] = [line]
        elif key is None:
            comments.append(line)
        else:
            fields[key].append(line)
    return (comments, fields) if "msgid" in fields else None


def plural_forms(fields: dict[str, list[str]]) -> list[str]:
    return [key for key in fields if key.startswith("msgstr[")]


def flags(line: str) -> list[str]:
    """The flags of a "#," comment line."""
    return [flag.strip() for flag in line[2:].split(",") if flag.strip()]


def is_fuzzy(comments: list[str]) -> bool:
    return any(line.startswith("#,") and "fuzzy" in flags(line) for line in comments)


def without_fuzzy(comments: list[str]) -> list[str]:
    kept = []
    for line in comments:
        if line.startswith("#,"):
            rest = [flag for flag in flags(line) if flag != "fuzzy"]
            if not rest:
                continue
            line = "#, " + ", ".join(rest)
        kept.append(line)
    return kept


def read_blocks(lang: str) -> list[str]:
    return (PO_DIR / f"{lang}.po").read_text(encoding="utf-8").split("\n\n")


def describe(fields: dict[str, list[str]]) -> dict:
    """The message as `todo` prints it and `apply` matches it."""
    message: dict = {"msgid": unquote(fields["msgid"])}
    if "msgctxt" in fields:
        message["context"] = unquote(fields["msgctxt"])
    if "msgid_plural" in fields:
        message["msgid_plural"] = unquote(fields["msgid_plural"])
        message["forms"] = len(plural_forms(fields))
    return message


def pending(lang: str) -> list[dict]:
    result: list[dict] = []
    for block in read_blocks(lang):
        entry = parse(block)
        if entry is None:
            continue
        comments, fields = entry
        msgid = unquote(fields["msgid"])
        if not msgid:  # the header
            continue
        forms = plural_forms(fields) or ["msgstr"]
        if not is_fuzzy(comments) and all(unquote(fields[form]) for form in forms):
            continue
        result.append(describe(fields))
    return result


def apply(translations: dict[str, list[dict]]) -> dict[str, int]:
    """Writes the translations; raises ValueError, before writing any file, if one does not fit."""
    texts, applied = {}, {}
    for lang, items in translations.items():
        if not (PO_DIR / f"{lang}.po").is_file():
            raise ValueError(f"{lang}: there is no po/{lang}.po")
        well_formed = isinstance(items, list) and all(
            isinstance(item, dict) and {"msgid", "msgstr"} <= item.keys() for item in items
        )
        if not well_formed:
            raise ValueError(f"{lang}: the value must be a list of objects, each with msgid and msgstr")
        messages = {(item["msgid"], item.get("context")): item["msgstr"] for item in items}
        blocks = read_blocks(lang)
        done = 0
        for i, block in enumerate(blocks):
            entry = parse(block)
            if entry is None:
                continue
            comments, fields = entry
            msgid = unquote(fields["msgid"])
            key = (msgid, unquote(fields["msgctxt"]) if "msgctxt" in fields else None)
            if key not in messages:
                continue
            value = messages.pop(key)
            forms = plural_forms(fields)
            if forms:
                if not isinstance(value, list) or len(value) != len(forms):
                    raise ValueError(f"{lang}: {msgid!r} needs a list of {len(forms)} plural forms")
                msgstr = [f"msgstr[{n}] {quote(text)}" for n, text in enumerate(value)]
            else:
                if not isinstance(value, str):
                    raise ValueError(f"{lang}: {msgid!r} is not a plural message, its value must be a string")
                msgstr = ["msgstr " + quote(value)]
            head = [line for key in ("msgctxt", "msgid", "msgid_plural") for line in fields.get(key, [])]
            # The last block keeps the file's final newline.
            end = "\n" if block.endswith("\n") else ""
            blocks[i] = "\n".join(without_fuzzy(comments) + head + msgstr) + end
            done += 1
        if messages:
            msgid, context = next(iter(messages))
            where = f" in context {context!r}" if context is not None else ""
            raise ValueError(f"{lang}: no message {msgid!r}{where}")
        texts[lang] = "\n\n".join(blocks)
        applied[lang] = done
    for lang, text in texts.items():
        (PO_DIR / f"{lang}.po").write_text(text, encoding="utf-8")
    return applied


def main(argv: list[str]) -> int:
    command = argv[1] if len(argv) > 1 else ""
    if command == "todo":
        todo = {lang: pending(lang) for lang in languages()}
        print(json.dumps({lang: ids for lang, ids in todo.items() if ids}, ensure_ascii=False, indent=2))
    elif command == "apply" and len(argv) == 3:
        translations = json.loads(Path(argv[2]).read_text(encoding="utf-8"))
        try:
            print(json.dumps(apply(translations)))
        except ValueError as error:
            print(f"nothing written: {error}", file=sys.stderr)
            return 1
    elif command == "status":
        for lang in languages():
            print(f"{lang}: {len(pending(lang))} pending")
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
